#if (boardUSE_OS)

//****************************************************Parameter Initialization**************************************************//
static TaskHandle_t S_tDispTaskHandle = NULL;

/***********************************************************************************************************************
 * 函数功能    : 绑定显示任务句柄
 * 说明(备注)  : 显示任务创建完成后调用一次; 未绑定时唤醒为空操作
 * 传入参数    : t_handle: 显示任务句柄
 * 输出参数    : 无
 * 返回值      : 无
 ************************************************************************************************************************/
void vDisp_PortSetTaskHandle(TaskHandle_t t_handle)
{
    S_tDispTaskHandle = t_handle;
}

/***********************************************************************************************************************
 * 函数功能    : 唤醒显示任务
 * 说明(备注)  : 事件入队/背光点亮后调用; 显示任务从"通知+超时"等待中提前返回,
 *               下一轮 vDisp_EnginePoll 立即处理事件与首帧强刷
 * 传入参数    : 无
 * 输出参数    : 无
 * 返回值      : 无
 ************************************************************************************************************************/
void vDisp_PortWakeTask(void)
{
    if (S_tDispTaskHandle != NULL)
        xTaskNotifyGive(S_tDispTaskHandle);
}

#endif  //boardUSE_OS

/***********************************************************************************************************************
 * 函数功能    : 渲染输出一轮 (适配原语)
 * 说明(备注)  : 转调项目件 vDisp_UiRefresh (EEZ ui_tick -> LVGL lv_timer_handler)
 * 传入参数    : 无
 * 输出参数    : 无
 * 返回值      : 无
 ************************************************************************************************************************/
void vDisp_PortUiRefresh(void)
{
    vDisp_UiRefresh();
}

/***********************************************************************************************************************
 * 函数功能    : 背光硬件开关 (适配原语)
 * 说明(备注)  : 转调接口层背光控制
 * 传入参数    : b_on: true=点亮, false=熄灭
 * 输出参数    : 无
 * 返回值      : 无
 ************************************************************************************************************************/
void vDisp_PortSetBacklight(bool b_on)
{
    vDisp_SetBacklight(b_on ? 1U : 0U);
}

/***********************************************************************************************************************
 * 函数功能    : 读取持久化息屏时间 (适配原语)
 * 说明(备注)  : 读取 APP 参数区显示记忆参数
 * 传入参数    : 无
 * 输出参数    : 无
 * 返回值      : uint16_t: 息屏时间秒数 (0=常亮)
 ************************************************************************************************************************/
uint16_t usDisp_PortGetAutoOffTime(void)
{
    return tAppMemParam.tDISP.usAutoOffTime;
}

/***********************************************************************************************************************
 * 函数功能    : 系统就绪判定 (适配原语)
 * 说明(备注)  : 显示模块初始化完成标志, false 时引擎锁定 INIT 页
 * 传入参数    : 无
 * 输出参数    : 无
 * 返回值      : true: 系统显示链路就绪
 ************************************************************************************************************************/
bool bDisp_PortIsSystemReady(void)
{
    return (tSysInfo.uInit.tFinish.bIF_DispTask != 0U);
}

/***********************************************************************************************************************
 * 函数功能    : 常亮亮屏提示钩子 (适配原语)
 * 说明(备注)  : 蜂鸣器使能时播放长音提示, 未使能为空操作
 * 传入参数    : 无
 * 输出参数    : 无
 * 返回值      : 无
 ************************************************************************************************************************/
void vDisp_PortBeepOnLightOn(void)
{
    #if (boardBUZ_EN)
    bBuz_Tweet(LONG_1);
    #endif  /* boardBUZ_EN */
}

#endif  /* boardDISPLAY_EN */
