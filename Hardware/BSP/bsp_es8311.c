/*****************************************************************************************************************
*                                            ES8311 音频编解码器驱动                                              *
*                                      封装层 - 基于espressif组件库                                              *
******************************************************************************************************************/
#include "BSP/bsp_es8311.h"
#include <esp_log.h>

static const char *TAG = "es8311";

// 全局对象
Es8311_T   tEs8311;

/*****************************************************************************************************************
-----函数功能    接口初始化
-----说明(备注)  初始化默认配置
-----传入参数    none
-----输出参数    none
-----返回值      none
******************************************************************************************************************/
void vEs8311_IfaceInit(void)
{
    // 默认时钟配置
    tEs8311.tClkCfg.mclk_inverted = false;
    tEs8311.tClkCfg.sclk_inverted = false;
    tEs8311.tClkCfg.mclk_from_mclk_pin = false;  // 从SCLK引脚获取MCLK
    tEs8311.tClkCfg.mclk_frequency = 0;          // 不使用MCLK引脚
    tEs8311.tClkCfg.sample_frequency = 48000;    // 48kHz采样率
    
    // 默认分辨率
    tEs8311.eResIn = ES8311_RESOLUTION_16;
    tEs8311.eResOut = ES8311_RESOLUTION_16;
    
    tEs8311.eDevState = DS_INIT;
    tEs8311.bMuteEn = false;
}

/*****************************************************************************************************************
-----函数功能    初始化
-----说明(备注)  初始化编解码器
-----传入参数    none
-----输出参数    none
-----返回值      小于0:失败   大于0:成功
******************************************************************************************************************/
s8 cEs8311_Init(void)
{
    esp_err_t e_ret;
    
    // 接口初始化
    vEs8311_IfaceInit();
    
    // 创建ES8311设备句柄 (根据网表: IO0_I2C_SDA, IO1_I2C_SCL)
    tEs8311.hDev = es8311_create(I2C_NUM_0, ES8311_I2C_ADDR);
    if(tEs8311.hDev == NULL)
    {
        ESP_LOGE(TAG, "Create handle failed");
        tEs8311.eDevState = DS_LOST;
        return -1;
    }
    
    // 初始化ES8311
    e_ret = es8311_init(tEs8311.hDev, &tEs8311.tClkCfg, tEs8311.eResIn, tEs8311.eResOut);
    if(e_ret != ESP_OK)
    {
        ESP_LOGE(TAG, "Init failed: %s", esp_err_to_name(e_ret));
        return -2;
    }
    
    tEs8311.eDevState = DS_WORK;
    ESP_LOGI(TAG, "Init success");
    
    return 1;
}

/*****************************************************************************************************************
-----函数功能    配置编解码器
-----说明(备注)  配置时钟和分辨率
-----传入参数    p_clk_cfg:时钟配置
                 e_res_in:输入分辨率
                 e_res_out:输出分辨率
-----输出参数    none
-----返回值      小于0:失败   大于0:成功
******************************************************************************************************************/
s8 cEs8311_Config(Es8311_ClockConfig_T *p_clk_cfg, Es8311_Resolution_E e_res_in, Es8311_Resolution_E e_res_out)
{
    esp_err_t e_ret;
    
    if(p_clk_cfg == NULL)
    {
        return -1;
    }
    
    tEs8311.tClkCfg = *p_clk_cfg;
    tEs8311.eResIn = e_res_in;
    tEs8311.eResOut = e_res_out;
    
    e_ret = es8311_init(tEs8311.hDev, p_clk_cfg, e_res_in, e_res_out);
    if(e_ret != ESP_OK)
    {
        return -2;
    }
    
    return 1;
}

/*****************************************************************************************************************
-----函数功能    设置音量
-----说明(备注)  设置输出音量
-----传入参数    uc_vol:音量值(0-100)
-----输出参数    none
-----返回值      小于0:失败   大于0:成功
******************************************************************************************************************/
s8 cEs8311_SetVolume(u8 uc_vol)
{
    esp_err_t e_ret;
    int i_vol_set;
    
    if(uc_vol > 100)
    {
        uc_vol = 100;
    }
    
    e_ret = es8311_voice_volume_set(tEs8311.hDev, (int)uc_vol, &i_vol_set);
    if(e_ret != ESP_OK)
    {
        return -1;
    }
    
    return 1;
}

/*****************************************************************************************************************
-----函数功能    获取音量
-----说明(备注)  获取当前音量
-----传入参数    p_vol:音量指针
-----输出参数    none
-----返回值      小于0:失败   大于0:成功
******************************************************************************************************************/
s8 cEs8311_GetVolume(u8 *p_vol)
{
    esp_err_t e_ret;
    int i_vol;
    
    if(p_vol == NULL)
    {
        return -1;
    }
    
    e_ret = es8311_voice_volume_get(tEs8311.hDev, &i_vol);
    if(e_ret != ESP_OK)
    {
        return -2;
    }
    
    *p_vol = (u8)i_vol;
    
    return 1;
}

/*****************************************************************************************************************
-----函数功能    设置MIC增益
-----说明(备注)  设置麦克风增益
-----传入参数    e_gain:增益值
-----输出参数    none
-----返回值      小于0:失败   大于0:成功
******************************************************************************************************************/
s8 cEs8311_SetMicGain(Es8311_MicGain_E e_gain)
{
    esp_err_t e_ret;
    
    e_ret = es8311_microphone_gain_set(tEs8311.hDev, e_gain);
    if(e_ret != ESP_OK)
    {
        return -1;
    }
    
    return 1;
}

/*****************************************************************************************************************
-----函数功能    设置静音
-----说明(备注)  设置静音状态
-----传入参数    b_mute:静音使能
-----输出参数    none
-----返回值      小于0:失败   大于0:成功
******************************************************************************************************************/
s8 cEs8311_SetMute(bool b_mute)
{
    esp_err_t e_ret;
    
    tEs8311.bMuteEn = b_mute;
    
    e_ret = es8311_voice_mute(tEs8311.hDev, b_mute);
    if(e_ret != ESP_OK)
    {
        return -1;
    }
    
    return 1;
}

/*****************************************************************************************************************
-----函数功能    配置麦克风
-----说明(备注)  配置模拟/数字麦克风
-----传入参数    b_digital_mic:是否使用数字麦克风
-----输出参数    none
-----返回值      小于0:失败   大于0:成功
******************************************************************************************************************/
s8 cEs8311_ConfigMic(bool b_digital_mic)
{
    esp_err_t e_ret;
    
    e_ret = es8311_microphone_config(tEs8311.hDev, b_digital_mic);
    if(e_ret != ESP_OK)
    {
        return -1;
    }
    
    return 1;
}