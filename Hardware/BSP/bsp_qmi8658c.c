/*****************************************************************************************************************
*                                            QMI8658C 6轴IMU传感器驱动                                          *
*                                      封装层 - 基于esp-idf-lib组件库                                            *
******************************************************************************************************************/
#include "BSP/bsp_qmi8658c.h"
#include <esp_log.h>

static const char *TAG = "qmi8658c";

// 全局对象
Qmi8658c_T   tQmi8658c;

/*****************************************************************************************************************
-----函数功能    接口初始化
-----说明(备注)  初始化I2C接口
-----传入参数    none
-----输出参数    none
-----返回值      none
******************************************************************************************************************/
void vQmi8658c_IfaceInit(void)
{
    // 默认配置
    tQmi8658c.tConfig.mode = QMI8658C_MODE_DUAL;
    tQmi8658c.tConfig.acc_scale = QMI8658C_ACC_SCALE_4G;
    tQmi8658c.tConfig.acc_odr = QMI8658C_ACC_ODR_250;
    tQmi8658c.tConfig.gyro_scale = QMI8658C_GYRO_SCALE_512DPS;
    tQmi8658c.tConfig.gyro_odr = QMI8658C_GYRO_ODR_250;
    
    tQmi8658c.eDevState = DS_INIT;
}

/*****************************************************************************************************************
-----函数功能    初始化
-----说明(备注)  初始化传感器
-----传入参数    none
-----输出参数    none
-----返回值      小于0:失败   大于0:成功
******************************************************************************************************************/
s8 cQmi8658c_Init(void)
{
    esp_err_t e_ret;
    
    // 接口初始化
    vQmi8658c_IfaceInit();
    
    // 初始化I2C设备描述符 (根据网表: IO0_I2C_SDA, IO1_I2C_SCL)
    e_ret = qmi8658c_init_desc(&tQmi8658c.tI2cDev, QMI8658C_I2C_ADDR, I2C_NUM_0, 0, 1);
    if(e_ret != ESP_OK)
    {
        ESP_LOGE(TAG, "I2C init failed");
        tQmi8658c.eDevState = DS_LOST;
        return -1;
    }
    
    // 配置传感器
    e_ret = qmi8658c_setup(&tQmi8658c.tI2cDev, &tQmi8658c.tConfig);
    if(e_ret != ESP_OK)
    {
        ESP_LOGE(TAG, "Setup failed");
        return -2;
    }
    
    tQmi8658c.eDevState = DS_WORK;
    ESP_LOGI(TAG, "Init success");
    
    return 1;
}

/*****************************************************************************************************************
-----函数功能    配置传感器
-----说明(备注)  配置量程、ODR等
-----传入参数    p_config:配置参数指针
-----输出参数    none
-----返回值      小于0:失败   大于0:成功
******************************************************************************************************************/
s8 cQmi8658c_Config(Qmi8658c_Config_T *p_config)
{
    esp_err_t e_ret;
    
    if(p_config == NULL)
    {
        return -1;
    }
    
    tQmi8658c.tConfig = *p_config;
    
    e_ret = qmi8658c_setup(&tQmi8658c.tI2cDev, p_config);
    if(e_ret != ESP_OK)
    {
        return -2;
    }
    
    return 1;
}

/*****************************************************************************************************************
-----函数功能    读取数据
-----说明(备注)  读取加速度计和陀螺仪数据
-----传入参数    p_data:数据指针
-----输出参数    none
-----返回值      小于0:失败   大于0:成功
******************************************************************************************************************/
s8 cQmi8658c_ReadData(Qmi8658c_Data_T *p_data)
{
    esp_err_t e_ret;
    
    if(p_data == NULL)
    {
        return -1;
    }
    
    e_ret = qmi8658c_read_data(&tQmi8658c.tI2cDev, p_data);
    if(e_ret != ESP_OK)
    {
        return -2;
    }
    
    // 更新全局数据
    tQmi8658c.tData = *p_data;
    
    return 1;
}

/*****************************************************************************************************************
-----函数功能    设置加速度计量程
-----说明(备注)  设置加速度计量程
-----传入参数    e_range:量程
-----输出参数    none
-----返回值      小于0:失败   大于0:成功
******************************************************************************************************************/
s8 cQmi8658c_SetAccRange(Qmi8658c_AccRange_E e_range)
{
    tQmi8658c.tConfig.acc_scale = e_range;
    return cQmi8658c_Config(&tQmi8658c.tConfig);
}

/*****************************************************************************************************************
-----函数功能    设置陀螺仪量程
-----说明(备注)  设置陀螺仪量程
-----传入参数    e_range:量程
-----输出参数    none
-----返回值      小于0:失败   大于0:成功
******************************************************************************************************************/
s8 cQmi8658c_SetGyrRange(Qmi8658c_GyrRange_E e_range)
{
    tQmi8658c.tConfig.gyro_scale = e_range;
    return cQmi8658c_Config(&tQmi8658c.tConfig);
}

/*****************************************************************************************************************
-----函数功能    获取温度
-----说明(备注)  获取当前温度值
-----传入参数    none
-----输出参数    none
-----返回值      温度值(℃)
******************************************************************************************************************/
float fQmi8658c_GetTemp(void)
{
    Qmi8658c_Data_T t_data;
    
    if(cQmi8658c_ReadData(&t_data) > 0)
    {
        return t_data.temperature;
    }
    
    return 0.0f;
}