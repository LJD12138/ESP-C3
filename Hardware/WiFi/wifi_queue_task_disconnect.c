/***********************************************************************************************************************
 * 函数功能    : WiFi 主动断开连接子任务
 * 说明(备注)  : 断开当前链路并复位状态
 * 传入参数    : p_task: 队列任务指针
 * 输出参数    : 无
 * 返回值      : 无
 ************************************************************************************************************************/
void v_wifi_queue_task_disconnect(Task_T *p_task)
{
	switch (p_task->ucStep)
	{
		case 0:
		{
			esp_wifi_disconnect();
			tWiFiInfo.eState = WIFI_STATE_DISCONNECTED;
			tWiFiInfo.cRssi  = -100;
			cQueue_GotoStep(p_task, STEP_END);
		}
		break;

		default:
		{
			cQueue_GotoStep(p_task, STEP_END);
		}
		break;
	}
}

#endif  /* boardWIFI_EN */
